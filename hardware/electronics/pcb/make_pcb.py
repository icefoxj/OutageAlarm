"""Writes the PCB (KiCad 8 .kicad_pcb) from board.py: outline, holes, parts, nets, tracks and silkscreen.

Runs with KiCad 8's Python (it needs pcbnew):
    "D:\\Program Files\\KiCad\\8.0\\bin\\python.exe" make_pcb.py [out.kicad_pcb]
Without an argument it writes ../kicad/OutageAlarm.kicad_pcb (check it with git diff).
Every part goes where board.py puts its pads; the script finds the rotation and stops if a pad lands elsewhere.
The silkscreen texts are drawn in the house mech font (mechfont.py) as filled polygons.
"""
import os
import sys
import tempfile
import uuid

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import board as BD  # noqa: E402
import kicad_lib as K  # noqa: E402
import mechfont as M  # noqa: E402

FP_DIR = K.share_dir("footprints")
OX, OY = 100.0, 150.0                          # KiCad position of the enclosure frame's origin


def V(x, y):                                   # y to the back = up on the screen
    return pcbnew.VECTOR2I(pcbnew.FromMM(OX + x), pcbnew.FromMM(OY - y))


def to_xy(p):
    return (round(pcbnew.ToMM(p.x) - OX, 3), round(OY - pcbnew.ToMM(p.y), 3))


def mm(v):
    return pcbnew.FromMM(v)


def uid(ref):                                  # the same UUID as the symbol in make_schematic.py
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "OutageAlarm/pcb/" + ref))


Bd = pcbnew.BOARD()
ds = Bd.GetDesignSettings()
ds.SetCopperLayerCount(2)
nc = ds.m_NetSettings.m_DefaultNetClass
nc.SetClearance(mm(BD.CLEARANCE))
nc.SetTrackWidth(mm(BD.TRACK))
nc.SetViaDiameter(mm(0.8))
nc.SetViaDrill(mm(0.4))
ds.m_MinClearance = mm(0.2)
ds.m_TrackMinWidth = mm(0.2)
ds.m_CopperEdgeClearance = mm(BD.EDGE_CLEARANCE)
ds.m_HoleClearance = mm(0.25)
ds.m_HoleToHoleMin = mm(0.25)
tb = Bd.GetTitleBlock()
tb.SetTitle(f"Outage Alarm {BD.CODE} - PCB")
tb.SetRevision("v" + BD.VERSION)
tb.SetCompany(BD.COMPANY)
tb.SetDate(BD.DATE)
tb.SetComment(0, "Generated by hardware/electronics/pcb/make_pcb.py from board.py: do not edit by hand")

NETS = {}


def net(name):
    if name not in NETS:
        ni = pcbnew.NETINFO_ITEM(Bd, name)
        Bd.Add(ni)
        NETS[name] = ni
    return NETS[name]


LAYERS = {"F.Cu": pcbnew.F_Cu, "B.Cu": pcbnew.B_Cu}
FPS = {}


def load(lib_id):
    lib, name = lib_id.split(":")
    fp = pcbnew.FootprintLoad(os.path.join(FP_DIR, lib + ".pretty"), name)
    if fp is None:
        raise KeyError(lib_id)
    fp.SetFPID(pcbnew.LIB_ID(lib, name))
    return fp


def pad_of(fp, num):
    return next(p for p in fp.Pads() if p.GetNumber() == num)


def place(p):
    """Put a part where board.py wants two of its pads."""
    fp = load(p["footprint"])
    Bd.Add(fp)
    fp.SetReference(p["ref"])
    fp.SetValue(p["value"])
    fp.Reference().SetVisible(False)          # the references are drawn in the mech font (REFS)
    fp.SetPath(pcbnew.KIID_PATH("/" + uid(p["ref"])))
    if hasattr(fp, "SetSheetname"):
        fp.SetSheetname("Root")
        fp.SetSheetfile(BD.NAME + ".kicad_sch")
    (na, ta), (nb, tb_) = list(p["place"].items())
    for rot in (0, 90, 180, 270):
        fp.SetOrientationDegrees(rot)
        fp.SetPosition(V(0, 0))
        pa = pad_of(fp, na).GetPosition()
        target = V(*ta)
        fp.SetPosition(pcbnew.VECTOR2I(fp.GetPosition().x + target.x - pa.x, fp.GetPosition().y + target.y - pa.y))
        bx, by = to_xy(pad_of(fp, nb).GetPosition())
        if abs(bx - tb_[0]) < 0.02 and abs(by - tb_[1]) < 0.02:
            break
    else:
        raise ValueError(f"{p['ref']}: no rotation puts pad {nb} at {tb_}")
    for pd in fp.Pads():
        n = p["pins"].get(pd.GetNumber())
        if n is None:
            n = "unconnected-(%s-Pad%s)" % (p["ref"], pd.GetNumber())
        pd.SetNet(net(n))
        got = to_xy(pd.GetPosition())
        want = BD.P[f"{p['ref']}.{pd.GetNumber()}"]
        if abs(got[0] - want[0]) > 0.02 or abs(got[1] - want[1]) > 0.02:
            raise ValueError(f"{p['ref']}.{pd.GetNumber()} at {got}, board.py says {want}")
    FPS[p["ref"]] = fp


def segment(a, b, layer, w=0.1):
    s = pcbnew.PCB_SHAPE(Bd)
    s.SetShape(pcbnew.SHAPE_T_SEGMENT)
    s.SetLayer(layer)
    s.SetWidth(mm(w))
    s.SetStart(V(*a))
    s.SetEnd(V(*b))
    Bd.Add(s)


def polyset(polys):
    ps = pcbnew.SHAPE_POLY_SET()
    for poly in polys:
        one = pcbnew.SHAPE_POLY_SET()
        one.NewOutline()
        for x, y in poly:
            one.Append(V(x, y).x, V(x, y).y)
        boolean(ps, "add", one)
    return ps


def boolean(a, op, b):
    f = {"add": a.BooleanAdd, "sub": a.BooleanSubtract, "and": a.BooleanIntersection}[op]
    try:
        f(b, pcbnew.SHAPE_POLY_SET.PM_FAST)
    except (TypeError, AttributeError):
        f(b)


def fill(ps, layer):
    try:
        ps.Fracture(pcbnew.SHAPE_POLY_SET.PM_FAST)
    except (TypeError, AttributeError):
        ps.Fracture()
    for i in range(ps.OutlineCount()):           # one shape per outline: KiCad draws only a polygon's first outline
        one = pcbnew.SHAPE_POLY_SET()
        one.AddOutline(ps.Outline(i))
        s = pcbnew.PCB_SHAPE(Bd)
        s.SetShape(pcbnew.SHAPE_T_POLY)
        s.SetFilled(True)
        s.SetLayer(layer)
        s.SetWidth(0)
        s.SetPolyShape(one)
        Bd.Add(s)


def text(txt, x, y, cap, w, anchor="left", layer=pcbnew.F_SilkS):
    fill(polyset(M.text(txt, x, y, cap, w, anchor, mirror=(layer == pcbnew.B_SilkS))), layer)


def build():
    for p in BD.PARTS:
        place(p)
    for i, (x, y) in enumerate(BD.SCREW_HOLES):
        h = load("MountingHole:MountingHole_3.2mm_M3")
        Bd.Add(h)
        h.SetReference(f"H{i + 1}")
        h.SetValue("M3")
        h.Reference().SetVisible(False)
        h.SetPath(pcbnew.KIID_PATH("/" + uid(f"H{i + 1}")))
        h.SetPosition(V(x, y))
        FPS[f"H{i + 1}"] = h
    pts = BD.OUTLINE
    for i in range(len(pts)):
        segment(pts[i], pts[(i + 1) % len(pts)], pcbnew.Edge_Cuts)
    # origin of the fabrication files: the board's front-left corner
    ds.SetAuxOrigin(V(BD.X0, BD.Y0))
    ds.SetGridOrigin(V(BD.X0, BD.Y0))

    # tracks
    for name, layer, path in BD.TRACKS:
        xy = [BD.P[q] if isinstance(q, str) else q for q in path]
        for a, b in zip(xy, xy[1:]):
            t = pcbnew.PCB_TRACK(Bd)
            t.SetStart(V(*a))
            t.SetEnd(V(*b))
            t.SetWidth(mm(BD.TRACK))
            t.SetLayer(LAYERS[layer])
            t.SetNet(net(name))
            Bd.Add(t)

    silk_top()
    for s, x, y, cap, w in BD.BOTTOM_TEXT:
        text(s, x, y, cap, w, "center", pcbnew.B_SilkS)


def silk_top():
    L = pcbnew.F_SilkS
    for s, x, y, anchor in BD.LABELS:
        text(s, x, y, BD.LABEL_CAP, BD.LABEL_W, anchor)
    for s, x, y, cap, w in BD.REFS:
        text(s, x, y, cap, w, "center")
    s, x, y, cap, w = BD.NC_MARK
    text(s, x, y, cap, w, "left")

    # placement outlines of the 18650 holder and the TP4056 module (they overhang the back edge)
    y_top = BD.Y0 + BD.H - 0.6
    for (x, y, wd, dp), label, sub in ((BD.HOLDER, "BT1 18650 HOLDER", "THIN TAPE - WIRES TO U1 B+ B-"),
                                       (BD.U1_OUTLINE, "U1", "TP4056")):
        segment((x, y_top), (x, y), L, 0.15)
        segment((x, y), (x + wd, y), L, 0.15)
        segment((x + wd, y), (x + wd, y_top), L, 0.15)
        cx, cy = x + wd / 2, (y + y_top) / 2
        text(label, cx, cy + 1.4, 1.8, 0.28, "center")
        text(sub, cx, cy - 1.4, 1.3, 0.21, "center")
    ux, uy, uw, _ = BD.U1_OUTLINE
    text("USB-C", ux + uw / 2, y_top - 1.8, 1.3, 0.21, "center")

    # title block: speed dashes, the band with the unit code knocked out, name, version and company, hazard stripes
    T = BD.TITLE_BLOCK
    v0, v1 = T["band"]
    h = v1 - v0
    x = T["x0"]
    dashes = []
    for dw in (0.8, 1.2, 1.8):
        dashes.append(M.slant(x, x + dw, v0, v1))
        x += dw + 0.9
    fill(polyset(dashes), L)
    band = polyset([M.slant(x, T["x1"] - h, v0, v1)])
    code_x = (x + T["x1"] - h) / 2 + h / 2
    boolean(band, "sub", polyset(M.text(BD.CODE, code_x, (v0 + v1) / 2, T["code_cap"], T["code_w"], "center")))
    fill(band, L)
    text(BD.TITLE, T["x0"], T["title_y"], T["title_cap"], T["title_w"], "left")
    title_end = T["x0"] + M.width(BD.TITLE, T["title_cap"], T["title_w"])
    text("PCB V" + BD.VERSION, T["x0"], T["line_y"], T["line_cap"], T["line_w"], "left")
    text(BD.COMPANY.upper(), title_end, T["line_y"], T["line_cap"], T["line_w"], "right")
    hv0, hv1 = T["hazard"]
    stripes = [M.slant(T["x0"] + i * 2 * T["stripe"], T["x0"] + i * 2 * T["stripe"] + T["stripe"], hv0, hv1)
               for i in range(5)]
    rule_x0 = T["x0"] + 10 * T["stripe"] + 1.2
    stripes.append(M.slant(rule_x0, title_end - 0.6, hv0, hv0 + 0.6))
    fill(polyset(stripes), L)


def save(out):
    tmp = os.path.join(tempfile.gettempdir(), "_" + BD.NAME + "_tmp.kicad_pcb")
    pcbnew.SaveBoard(tmp, Bd)
    b = pcbnew.LoadBoard(tmp)
    pcbnew.SaveBoard(out, b)
    return out


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "kicad", BD.NAME + ".kicad_pcb")
    build()
    print("wrote", save(out))
